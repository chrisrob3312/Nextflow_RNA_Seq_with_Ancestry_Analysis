#!/usr/bin/env Rscript

# ============================================================================
# Integrated Visualization - Creates summary figures across all modules
# ============================================================================

suppressPackageStartupMessages({
    library(optparse)
    library(ggplot2)
    library(pheatmap)
    library(patchwork)
    library(RColorBrewer)
    library(ggrepel)
})

option_list <- list(
    make_option("--de-dir", type = "character", default = NULL),
    make_option("--pathway-dir", type = "character", default = NULL),
    make_option("--immune-dir", type = "character", default = NULL),
    make_option("--ancestry-dir", type = "character", default = NULL),
    make_option("--wgcna-dir", type = "character", default = NULL),
    make_option("--pharma-dir", type = "character", default = NULL),
    make_option("--metadata", type = "character"),
    make_option("--output-dir", type = "character", default = "figures"),
    make_option("--format", type = "character", default = "png,pdf")
)
opt <- parse_args(OptionParser(option_list = option_list))

formats <- trimws(unlist(strsplit(opt$format, ",")))

save_plot <- function(p, name, width = 10, height = 8) {
    for (fmt in formats) {
        ggsave(file.path(opt$`output-dir`, "overview", paste0(name, ".", fmt)),
               p, width = width, height = height)
    }
}

metadata <- read.delim(opt$metadata, check.names = FALSE)
rownames(metadata) <- metadata$sample_id

# ---- Overview: Sample demographics ----
cat("Creating overview plots...\n")

if ("cytomolecular_subgroup" %in% colnames(metadata)) {
    p1 <- ggplot(metadata, aes(x = cytomolecular_subgroup, fill = cytomolecular_subgroup)) +
        geom_bar() + coord_flip() +
        labs(title = "Cytomolecular Subgroup Distribution", x = "", y = "Count") +
        theme_bw() + theme(legend.position = "none")
    save_plot(p1, "subgroup_distribution")
}

if ("relapse_status" %in% colnames(metadata) && "cytomolecular_subgroup" %in% colnames(metadata)) {
    p2 <- ggplot(metadata[metadata$relapse_status != "NA", ],
                  aes(x = cytomolecular_subgroup, fill = relapse_status)) +
        geom_bar(position = "fill") + coord_flip() +
        scale_y_continuous(labels = scales::percent) +
        labs(title = "Relapse Rate by Subgroup", x = "", y = "Proportion") +
        theme_bw()
    save_plot(p2, "relapse_by_subgroup")
}

if ("age" %in% colnames(metadata)) {
    metadata$age_num <- as.numeric(metadata$age)
    p3 <- ggplot(metadata[!is.na(metadata$age_num), ],
                  aes(x = age_num, fill = relapse_status)) +
        geom_histogram(bins = 15, alpha = 0.7, position = "identity") +
        labs(title = "Age Distribution at Diagnosis", x = "Age (years)", y = "Count") +
        theme_bw()
    save_plot(p3, "age_distribution", width = 8, height = 5)
}

# ---- DE Summary ----
if (!is.null(opt$`de-dir`) && dir.exists(opt$`de-dir`)) {
    cat("Creating DE summary plots...\n")
    summary_file <- file.path(opt$`de-dir`, "de_summary.tsv")
    if (file.exists(summary_file)) {
        de_summary <- read.delim(summary_file, check.names = FALSE)
        p4 <- ggplot(de_summary, aes(x = reorder(contrast, n_sig_total), y = n_sig_total, fill = subgroup)) +
            geom_col() + coord_flip() +
            labs(title = "Significant DE Genes per Contrast", x = "", y = "N Significant") +
            theme_bw()
        save_plot(p4, "de_summary_barplot", width = 12, height = 8)
    }
}

# ---- Ancestry ----
if (!is.null(opt$`ancestry-dir`) && dir.exists(opt$`ancestry-dir`)) {
    cat("Creating ancestry plots...\n")
    # Ancestry plots are generated by ancestry_inference.py
}

# ---- Immune ----
if (!is.null(opt$`immune-dir`) && dir.exists(opt$`immune-dir`)) {
    cat("Creating immune overview plots...\n")
}

cat("Visualization complete.\n")
